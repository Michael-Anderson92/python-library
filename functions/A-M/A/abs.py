# abs.py - Absolute value function

# Basic examples
print("abs(-5):", abs(-5))
print("abs(3.14):", abs(3.14))
print("abs(-42):", abs(-42))
print("abs(0):", abs(0))

# With variables
number = -100
number2 = 25.542
print(f"abs({number}):", abs(number))
print(f"abs({number2}):", abs(number2))

# # Complex numbers
# print("abs(-3 + 4j):", abs(-3 + 4j))
complexnumber = -3 + 4j
print(f"abs({complexnumber}):", abs(complexnumber))